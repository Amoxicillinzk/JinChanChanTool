using System.Runtime.CompilerServices;

namespace JinChanChanTool.Services.AICoach;

/// <summary>
/// 把 V4.1 的运营决策原则落到本地。这个文件不是会话记忆；换任何模型时都可以直接提供给它。
/// </summary>
public static class V41DecisionAssets
{
    public static string RulebookPath => Path.Combine(
        LineupGenerationAssets.RootDirectory,
        "04-V4.1对局决策规则.md");

    [ModuleInitializer]
    public static void Initialize()
    {
        try
        {
            Directory.CreateDirectory(LineupGenerationAssets.RootDirectory);
            File.WriteAllText(RulebookPath, RulebookText);
        }
        catch { }
    }

    public const string RulebookText = """
# JinChanChanTool V4.1 对局决策规则

## 目标
本规则的目标是提高长期吃分稳定性与决策质量，不承诺单局必胜。模型必须优先减少四类高频掉分错误：
1. 低血量仍然贪人口或贪50金币；
2. D牌阵错过对应等级窗口仍强追三星；
3. 缺少专属强化/关键纹章仍硬玩条件阵容；
4. 只因单轮商店来牌就进行高成本转阵。

## 数据优先级
1. 当前上场棋盘与羁绊；
2. 阶段、等级、金币、血量；
3. 已确认的装备、纹章、强化符文；
4. 最近一次手动刷新得到的 MetaTFT 数据；
5. 当前商店五张牌。

商店是弱信号。棋盘、血量、经济、装备和强化是强信号。

## 阵容阶段
LineUps.json 中：
- SubLineUps[0] = 前期过渡
- SubLineUps[1] = 中期骨架
- SubLineUps[2] = 后期成型

评估当前棋盘时必须使用当前阶段对应的 SubLineUp，而不是拿最终九人口阵容去要求二阶段棋盘。

## 锁阵原则
只有在以下条件同时较好时才可以“锁定”：
- 当前阶段棋盘/羁绊明显契合；
- 装备或纹章方向支持；
- 运营节奏没有与当前血量/金币冲突；
- 第一候选相对第二候选有明显优势；
- 输入置信度足够。

否则使用“主推”或“观察”，保留转阵空间。

## 血量止损
- HP <= 30：优先活过下一轮。可以主动花钱D牌、合成通用成装、放弃长期经济目标。
- HP 31~50：不能连续空过。速8/速9阵容必须先判断当前棋盘是否能稳住。
- HP >= 65 且经济健康：允许追求更高上限和高人口阵容。

## D牌窗口
- 5级D牌阵：5级是核心窗口；升过6/7后如果核心数量不领先，应降低追三星优先级。
- 6级D牌阵：6级主D；血量健康时卡利息，低血时可以D到30/20稳血。
- 7级D牌阵：到7再启动；不要在5/6级提前把钱D空。
- 所有D牌阵：三星不是目的，稳定战力与名次才是目的。

## Fast 8 / Fast 9
Fast 8：
- 血量和经济健康时优先到8进入四费主D窗口；
- 7级低血时允许先D一轮止血；
- 不能为了“标准节奏”空过到被抬走。

Fast 9：
- 只适合明显健康的血量与经济；
- 8级棋盘不稳定时必须先把四费/前排提到两星；
- 低于约55~60血时，除非棋盘非常强，否则不要机械速9。

## 装备
- 已确认成装 > 可以直接合成的散件 > 未确认装备。
- 没有可靠装备识别时，不得虚构装备。
- 低血时通用强力成装优先于等待完美三件套。
- 主C与主坦至少要各有一套可工作的装备路线，不能只堆一侧。

## 强化符文与纹章
- 专属强化是硬条件时，缺失必须显著降权甚至“不建议”。
- 纹章如果能直接服务目标主羁绊，是强方向信号。
- 经济类强化偏向 Fast 8/Fast 9；刷新/复制/商店类强化偏向 reroll；纯战力强化在低血时权重更高。
- 不知道某个强化具体效果时只能按名称语义弱匹配，不得编造效果。

## Meta 数据
- Tier、平均名次、前四率、登顶率是先验，不是无条件答案。
- 冷门高数据阵容可以保留，但登场率过低时要降低确定性。
- Meta 缓存超过48小时应提示刷新；超过96小时不得高置信度锁阵。

## 转阵成本
进入中后期后，已经两星、已经持有成装、已经形成羁绊的棋盘有真实沉没成本。
新阵容仅因为“版本更强”但需要替换大量当前单位时，应扣除转阵分。
低血时转阵成本权重进一步提高。

## 模型输出要求
必须给可直接执行的指令，而不是泛泛攻略：
- 主推阵容
- 现在升人口 / D牌 / 存钱 / 合装备中的哪一个
- 什么时候停D
- 什么条件触发转阵
- 第二候选
- 当前最不能做的一件事
""";
}
